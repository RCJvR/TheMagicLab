#!/usr/bin/env node
// Builds math-magician/toolbox-data.js: an index of every interactive tool
// (calculators, explorers, graphers) embedded in the Math Magician lessons,
// for the Toolbox page. Run after changing lesson content:
//   node scripts/build-math-toolbox.js
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..', 'math-magician');
const GRADES = [8, 9, 10, 11, 12];

function loadChapter(file) {
  let data = null;
  const sandbox = { MathMagician: { registerChapter(num, d) { data = { num, ...d }; } }, window: {}, console };
  sandbox.window = sandbox;
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), sandbox, { filename: file });
  return data;
}

// A tool is a box title that starts with one of the lesson markers.
const TITLE = /class="def-box-title"[^>]*>\s*([\s\S]*?)<\/div>/g;
const MARK = /^(?:&#127918;|🎮)\s*(?:Try it|Probeer dit)\s*(?:&#8212;|—|-)\s*|^(?:🔢|📈|🧮|📊|📐|🎲|💰)\s*/u;
const decode = (s) => s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&#8212;/g, '—').replace(/&#8722;/g, '−')
  .replace(/&#178;/g, '²').replace(/&#179;/g, '³').replace(/&#(\d+);/g, (m, n) => String.fromCodePoint(+n)).replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

function toolsIn(topic) {
  // Every string in the topic (lesson, examples, practice…), wherever the widget sits.
  const strings = [];
  (function walk(v) {
    if (typeof v === 'string') strings.push(v);
    else if (v && typeof v === 'object') Object.values(v).forEach(walk);
  })(topic);
  const html = strings.join('\n');
  const out = [];
  let m;
  TITLE.lastIndex = 0;
  while ((m = TITLE.exec(html))) {
    const raw = decode(m[1]);
    if (!MARK.test(raw)) continue;
    const name = raw.replace(MARK, '').trim();
    if (name && !out.includes(name)) out.push(name);
  }
  return out;
}

const entries = [];
for (const g of GRADES) {
  const dir = path.join(ROOT, 'gr' + g);
  const chapters = fs.readdirSync(dir).filter(f => /^ch\d+\.js$/.test(f)).sort((a, b) => parseInt(a.slice(2)) - parseInt(b.slice(2)));
  for (const f of chapters) {
    const en = loadChapter(path.join(dir, f));
    const afFile = path.join(dir, f.replace('.js', '.af.js'));
    const af = fs.existsSync(afFile) ? loadChapter(afFile) : null;
    if (!en || !en.topics) continue;
    en.topics.forEach((t, i) => {
      const tools = toolsIn(t);
      if (!tools.length) return;
      const ta = af && af.topics && (af.topics.find(x => x.id === t.id) || af.topics[i]);
      const toolsAf = ta ? toolsIn(ta) : [];
      entries.push({
        g, ch: en.num, id: t.id, topic: t.name, topicAf: ta ? ta.name : t.name,
        tools: tools.map((n, k) => [n, toolsAf.length === tools.length ? toolsAf[k] : n]),
      });
    });
  }
}
const count = entries.reduce((n, e) => n + e.tools.length, 0);
const out = `// Generated by scripts/build-math-toolbox.js — do not edit by hand.\n// ${count} tools across ${entries.length} lesson topics.\nwindow.MM_TOOLBOX = ${JSON.stringify(entries)};\n`;
fs.writeFileSync(path.join(ROOT, 'toolbox-data.js'), out);
console.log(`toolbox-data.js: ${count} tools in ${entries.length} topics`);
