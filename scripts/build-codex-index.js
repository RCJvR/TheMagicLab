#!/usr/bin/env node
// Computer Codex: writes assets/codex-lesson-index.js (grade → { lesson id: title },
// for the teacher dashboard) and the "computer-codex" section of lesson-catalog.js
// (the assignment lesson picker, with each lesson's fixed id as `ref`).
// Lesson ids and grades come from assets/computer-codex.js itself, so they always match.
// Run after adding, renaming or moving Computer Codex lessons:  node scripts/build-codex-index.js
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const { setCatalogSection } = require('./lesson-catalog-file');
const ROOT = path.join(__dirname, '..');

// Run the lesson data and id code only (everything before the app logic).
let src = fs.readFileSync(path.join(ROOT, 'assets', 'computer-codex.js'), 'utf8');
src = src.slice(0, src.indexOf('// APP LOGIC')) + '\nglobalThis.__tracks = TRACKS;';
const nothing = () => null;
const ctx = { window: {}, console, document: { getElementById: nothing, querySelector: nothing, querySelectorAll: () => [], addEventListener() {} } };
ctx.globalThis = ctx;
vm.runInNewContext(src, ctx);

const TRACK_NAMES = { coding: 'Coding & Robotics', 'cat-caps': 'CAT — CAPS', 'cat-ieb': 'CAT — IEB', 'it-caps': 'IT — CAPS', 'it-ieb': 'IT — IEB' };
const plain = s => s.replace(/&amp;/g, '&');
const index = {}, groups = [];
for (const [track, t] of Object.entries(ctx.__tracks)) {
  const byGrade = {};
  t.lessons.forEach(les => {
    (index[les.grade] = index[les.grade] || {})[les.key] = plain(les.title);
    (byGrade[les.grade] = byGrade[les.grade] || []).push({ value: plain(les.title), label: plain(les.title), ref: `cc:${les.grade}:${les.key}` });
  });
  Object.entries(byGrade).forEach(([g, lessons]) =>
    groups.push({ group: track === 'coding' ? `${TRACK_NAMES[track]} (Gr 8–9)` : `${TRACK_NAMES[track]} · Grade ${g}`, lessons }));
}

const body = Object.entries(index).map(([g, m]) => `  ${g}: {\n` + Object.entries(m).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n') + '\n  }').join(',\n');
fs.writeFileSync(path.join(ROOT, 'assets', 'codex-lesson-index.js'),
  `/* Computer Codex lesson names by grade: lesson id → title (Coding & Robotics counts as Grade 8).\n   Generated by scripts/build-codex-index.js; used by the teacher dashboard. */\nwindow.CC_LESSON_INDEX = {\n${body}\n};\n`);
setCatalogSection('computer-codex', groups);
console.log('lessons per grade:', Object.fromEntries(Object.entries(index).map(([g, m]) => [g, Object.keys(m).length])), '| picker groups:', groups.length);
