#!/usr/bin/env node
// Builds science-sage/toolbox-data.js: every Science Sage lesson that has
// interactive simulators on its Explore tab, with the simulators' names in
// English and Afrikaans, for the Science Toolbox page. Run after changing
// lesson content:
//   node scripts/build-science-toolbox.js
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'science-sage');
const GRADES = [7, 8, 9, 10, 11, 12];
const TOOLWORD = /(Simulator|Simulasie|Calculator|Sakrekenaar|Rekenaar|Explorer|Verkenner|Builder|Bouer|Sandbox|Speelarea|Visuali[sz]er|Balancer|Balanseerder|Lab\b|Laboratorium|Diagram|Model|Grafiek|Graph)/i;
const NAMED = { amp: '&', nbsp: ' ', mdash: '—', ndash: '–', sup2: '²', sup3: '³', rarr: '→', harr: '↔', rlarr: '⇌', deg: '°', middot: '·', times: '×', lt: '<', gt: '>', quot: '"', apos: "'" };
const decode = (s) => s.replace(/<[^>]+>/g, '')
  .replace(/&#x([0-9a-f]+);/gi, (m, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (m, n) => String.fromCodePoint(+n))
  .replace(/&([a-z0-9]+);/gi, (m, n) => NAMED[n] != null ? NAMED[n] : '')
  .replace(/\s+/g, ' ').trim();
// "Le Chatelier Simulator — Haber Process: …" → "Le Chatelier Simulator"
const short = (t) => t.split(/\s[—–]\s/)[0].trim();

function explore(html) {
  const i = html.indexOf('id="tab-explore"');
  if (i < 0) return [];
  // the Explore panel runs until the next tab panel
  const j = html.indexOf('class="tab-panel"', i + 20);
  const part = html.slice(i, j < 0 ? undefined : j);
  const names = [];
  const re = /<(h3|h4|div class="[^"]*title[^"]*")[^>]*>([\s\S]*?)<\/(h3|h4|div)>/g;
  let m;
  while ((m = re.exec(part))) {
    const t = decode(m[2]);
    const n = short(t);
    if (n && n.length < 80 && !n.includes('${') && !/\?$/.test(n) && TOOLWORD.test(n) && !names.includes(n)) names.push(n);
  }
  if (!names.length) {
    const h = /<h3[^>]*>([\s\S]*?)<\/h3>/.exec(part);
    const n = h ? short(decode(h[1])) : '';
    if (n && !n.includes('${') && !/\?$/.test(n)) names.push(n);
  }
  return names;
}
const titleOf = (html) => decode((/<title>([\s\S]*?)<\/title>/.exec(html) || [, ''])[1]).split(/\s[—·-]\s/)[0];

const out = [];
for (const g of GRADES) {
  const gdir = path.join(ROOT, 'gr' + g);
  if (!fs.existsSync(gdir)) continue;
  for (const strand of fs.readdirSync(gdir).sort()) {
    const sdir = path.join(gdir, strand);
    if (!fs.statSync(sdir).isDirectory()) continue;
    for (const f of fs.readdirSync(sdir).filter(f => f.endsWith('.html') && !f.endsWith('.af.html')).sort()) {
      const html = fs.readFileSync(path.join(sdir, f), 'utf8');
      const tools = explore(html);
      if (!tools.length) continue;
      const afPath = path.join(sdir, f.replace('.html', '.af.html'));
      const afHtml = fs.existsSync(afPath) ? fs.readFileSync(afPath, 'utf8') : '';
      const toolsAf = afHtml ? explore(afHtml) : [];
      out.push({
        g, strand, file: `gr${g}/${strand}/${f}`, af: afHtml ? `gr${g}/${strand}/${f.replace('.html', '.af.html')}` : null,
        topic: titleOf(html), topicAf: afHtml ? titleOf(afHtml) : titleOf(html),
        tools: tools.map((t, k) => [t, toolsAf.length === tools.length ? toolsAf[k] : t]),
      });
    }
  }
}
const count = out.reduce((n, e) => n + e.tools.length, 0);
fs.writeFileSync(path.join(ROOT, 'toolbox-data.js'), `// Generated by scripts/build-science-toolbox.js — do not edit by hand.\n// ${count} simulators across ${out.length} lessons.\nwindow.SS_TOOLBOX = ${JSON.stringify(out)};\n`);
console.log(`science-sage/toolbox-data.js: ${count} simulators in ${out.length} lessons`);
