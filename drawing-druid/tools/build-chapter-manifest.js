// node drawing-druid/tools/build-chapter-manifest.js  (needs the local server on :8770 and puppeteer-core)
// Writes drawing-druid/chapter-manifest.js: every chapter's exercise ids, used by the Course
// Drawings page to decide when a learner has completed a chapter. Re-run after adding exercises.
const path = require('path'), fs = require('fs');
const puppeteer = require(process.env.PUPPETEER || 'puppeteer-core');
const ROOT = path.join(__dirname, '..', 'chapters');
const SKIP = new Set(['resources.html', 'practical-assessment-task.html', 'course-drawings.html']);
(async () => {
  const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new' });
  const out = {};
  for (const f of fs.readdirSync(ROOT).filter(f => f.endsWith('.html') && !SKIP.has(f))) {
    const p = await b.newPage(); await p.setRequestInterception(true);
    p.on('request', r => { const u = r.url(); if (/(auth|require-auth|progress|xp|contact-button|supabase)\.js/.test(u) || !u.startsWith('http://localhost:8770/')) return r.abort(); r.continue(); });
    await p.goto('http://localhost:8770/drawing-druid/chapters/' + f, { waitUntil: 'load' });
    out[f.replace('.html', '')] = await p.evaluate(() => (window.CONSTRUCTION_ORDER || []).filter(id => !/-parts$/.test(id)));
    await p.close();
  }
  await b.close();
  fs.writeFileSync(path.join(__dirname, '..', 'chapter-manifest.js'),
    '// Generated by tools/build-chapter-manifest.js — the exercise ids of every chapter.\nwindow.DD_CHAPTERS = ' + JSON.stringify(out, null, 1) + ';\n');
  console.log(Object.entries(out).map(([k, v]) => k + ' ' + v.length).join('\n'));
})();
